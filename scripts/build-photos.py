#!/usr/bin/env python3
"""
Build the local derivatives for the photography series.

Reads photos.json (the single source of truth for the edit), writes
assets/full/<slug>.jpg and assets/thumb/<slug>.jpg, and refreshes
js/photos.js + supabase/seed-photos.sql so the gallery and the future
cloud database always match the manifest.

  python3 scripts/build-photos.py [--force]

Source files are read from photos-inbox/ (gitignored). sips re-encodes,
which also drops EXIF/GPS metadata before anything is published.
"""
import argparse
import glob
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INBOX = os.path.join(ROOT, "photos-inbox")
SIZES = {"full": 1700, "thumb": 720}
QUALITY = "78"


def find_source(n):
    for pat in ("Aesthetic_Vibes_%02d.*" % n, "Aesthetic_Vibes_%d.*" % n):
        hits = glob.glob(os.path.join(INBOX, pat))
        if hits:
            return sorted(hits)[0]
    return None


def resize(src, dst, longest):
    cmd = ["sips", "-s", "format", "jpeg", "-s", "formatOptions", QUALITY,
           "-Z", str(longest), src, "--out", dst]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0 or not os.path.exists(dst):
        raise RuntimeError("sips failed for %s\n%s" % (src, res.stderr.strip()))


def dimensions(path):
    out = subprocess.run(["sips", "-g", "pixelWidth", "-g", "pixelHeight", path],
                         capture_output=True, text=True).stdout
    w = h = 0
    for line in out.splitlines():
        if "pixelWidth" in line:
            w = int(line.split(":")[1])
        if "pixelHeight" in line:
            h = int(line.split(":")[1])
    return w, h


def js_str(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="rebuild existing derivatives")
    args = ap.parse_args()

    man = json.load(open(os.path.join(ROOT, "photos.json"), encoding="utf-8"))
    photos = man["photos"]
    chapters = man["chapters"]

    os.makedirs(os.path.join(ROOT, "assets", "full"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "assets", "thumb"), exist_ok=True)

    rows = []
    total = 0
    for i, p in enumerate(photos, 1):
        src = find_source(p["src"])
        if not src:
            sys.exit("missing source for #%s (%s)" % (p["src"], p["slug"]))
        outs = {}
        for kind, size in SIZES.items():
            dst = os.path.join(ROOT, "assets", kind, p["slug"] + ".jpg")
            outs[kind] = dst
            if args.force or not os.path.exists(dst):
                resize(src, dst, size)
            total += os.path.getsize(dst)
        w, h = dimensions(outs["full"])
        rows.append({
            "f": p["slug"], "t": p["title_ar"], "en": p["title_en"],
            "c": "photo", "tags": p["tags"], "ch": p["chapter"], "w": w, "h": h,
        })
        print("[%2d/%d] %-32s %4dx%-4d %s" % (i, len(photos), p["slug"], w, h, p["chapter"]))

    # ---- js/photos.js — consumed by index.html
    lines = [
        "/* auto-generated by scripts/build-photos.py — do not edit by hand.",
        "   Edit photos.json and rebuild instead. */",
        "window.PHOTO_CHAPTERS = %s;" % json.dumps(chapters, ensure_ascii=False),
        "window.PHOTO_ITEMS = [",
    ]
    for r in rows:
        lines.append("  { f:%s, t:%s, en:%s, c:\"photo\", tags:%s, ch:%s, w:%d, h:%d }," % (
            js_str(r["f"]), js_str(r["t"]), js_str(r["en"]),
            json.dumps(r["tags"], ensure_ascii=False), js_str(r["ch"]), r["w"], r["h"]))
    lines[-1] = lines[-1].rstrip(",")
    lines += ["];", ""]
    open(os.path.join(ROOT, "js", "photos.js"), "w", encoding="utf-8").write("\n".join(lines))

    # ---- supabase/seed-photos.sql — same rows, for the day Supabase is wired up
    sql = ["-- auto-generated from photos.json — %d photographs" % len(rows), ""]
    for i, r in enumerate(rows, 1):
        sql.append(
            "insert into public.works (slug,title_ar,title_en,cat,tags,thumb_url,full_url,year,sort,published)\n"
            "values (%s,%s,%s,'photo',%s,'assets/thumb/%s.jpg','assets/full/%s.jpg',2026,%d,true)\n"
            "on conflict (slug) do update set title_ar=excluded.title_ar, title_en=excluded.title_en,\n"
            "  tags=excluded.tags, thumb_url=excluded.thumb_url, full_url=excluded.full_url,\n"
            "  sort=excluded.sort, published=excluded.published;" % (
                "'" + r["f"] + "'", "'" + r["t"] + "'", "'" + r["en"].replace("'", "''") + "'",
                "'{" + ",".join('"%s"' % t for t in r["tags"]) + "}'", r["f"], r["f"], 36 + i))
    open(os.path.join(ROOT, "supabase", "seed-photos.sql"), "w", encoding="utf-8").write("\n\n".join(sql) + "\n")

    print("\n%d photographs — %.1f MB of derivatives" % (len(rows), total / 1048576.0))
    print("wrote js/photos.js and supabase/seed-photos.sql")


if __name__ == "__main__":
    main()
